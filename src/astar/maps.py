def simple_graph() -> Graph:
    """Small 10-vertex "city road network", easy to check by hand. Edge weight = Euclidean distance (some congested roads ×1.5)."""
    positions = {
        "A": (0, 0),
        "B": (2, 1),
        "C": (1, 3),
        "D": (4, 0),
        "E": (4, 3),
        "F": (6, 1),
        "G": (3, 5),
        "H": (6, 4),
        "I": (8, 2),
        "J": (8, 5),
    }
    graph = Graph(name="simple_graph")
    for vertex, position in positions.items():
        graph.add_vertex(vertex, position)
    for source, target in [
        "AB",
        "AC",
        "BD",
        "BE",
        "CG",
        "CE",
        "DF",
        "EF",
        "EH",
        "GH",
        "FI",
        "HJ",
        "IJ",
        "HI",
    ]:
        graph.add_edge(source, target)
    for source, target in ["BE", "FI"]:  # congested roads
        graph.add_edge(source, target, graph.distance(source, target) * 1.5)
    graph.start, graph.goal = "A", "J"
    return graph


def random_road_graph(
    vertex_count: int = 800,
    neighbors_per_vertex: int = 4,
    seed: int = 0,
    max_detour: float = 0.3,
    lake_count: int = 4,
) -> Graph:
    """Random "road network": scatter points on a 100×60 plane (with several circular "lakes" cut out), and
    connect each point to its ``neighbors_per_vertex`` nearest neighbors; edge weight = Euclidean distance ×
    U(1, 1+max_detour), so the Euclidean heuristic is admissible. Guaranteed to be connected."""
    rng = np.random.default_rng(seed)
    area_width, area_height = 100.0, 60.0
    lakes = [
        (rng.uniform(25, 75), rng.uniform(10, 50), rng.uniform(6, 12))
        for _ in range(lake_count)
    ]
    points: list[tuple[float, float]] = []
    while len(points) < vertex_count:
        x, y = rng.uniform(0, area_width), rng.uniform(0, area_height)
        if all(
            math.hypot(x - lake_x, y - lake_y) > lake_radius
            for lake_x, lake_y, lake_radius in lakes
        ):
            points.append((x, y))
    point_array = np.array(points)
    graph = Graph(name="road_graph")
    for vertex, position in enumerate(points):
        graph.add_vertex(vertex, position)
    squared_distances = ((point_array[:, None, :] - point_array[None, :, :]) ** 2).sum(
        -1
    )
    np.fill_diagonal(squared_distances, np.inf)
    nearest_neighbors = np.argsort(squared_distances, axis=1)[:, :neighbors_per_vertex]
    for source in range(vertex_count):
        for target in nearest_neighbors[source]:
            target = int(target)
            if target not in graph.adjacency[source]:
                detour_factor = rng.uniform(1, 1 + max_detour)
                graph.add_edge(
                    source, target, graph.distance(source, target) * detour_factor
                )

    # Connectivity repair: link each non-main component to the nearest vertex of the main component
    def connected_components() -> list[set[int]]:
        visited, components = set(), []
        for seed_vertex in range(vertex_count):
            if seed_vertex in visited:
                continue
            component, stack = set(), [seed_vertex]
            while stack:
                vertex = stack.pop()
                if vertex in component:
                    continue
                component.add(vertex)
                stack.extend(
                    neighbor
                    for neighbor in graph.adjacency[vertex]
                    if neighbor not in component
                )
            visited |= component
            components.append(component)
        return sorted(components, key=len, reverse=True)

    components = connected_components()
    main_component = components[0]
    for component in components[1:]:
        component_vertices = np.array(sorted(component))
        main_vertices = np.array(sorted(main_component))
        between = squared_distances[np.ix_(component_vertices, main_vertices)]
        component_index, main_index = np.unravel_index(
            np.argmin(between), between.shape
        )
        graph.add_edge(
            int(component_vertices[component_index]), int(main_vertices[main_index])
        )
        main_component |= component

    graph.start = int(np.argmin(point_array[:, 0] + point_array[:, 1]))  # bottom-left
    graph.goal = int(np.argmax(point_array[:, 0] + point_array[:, 1]))  # top-right
    return graph


