def simple_grid(diagonal: bool = False) -> GridMap:
    """Simple 15×25 map: a bracket-shaped wall separates the start from the goal."""
    return GridMap.from_ascii(SIMPLE_ASCII, diagonal=diagonal, name="simple")


def open_grid(height: int = 30, width: int = 50, diagonal: bool = False) -> GridMap:
    """Obstacle-free open field: best shows how a heuristic narrows the region that gets expanded."""
    return GridMap(
        np.ones((height, width)),
        diagonal=diagonal,
        start=(height // 2, 3),
        goal=(height // 2, width - 4),
        name="open",
    )


def maze_grid(
    height: int = 41,
    width: int = 61,
    loop_ratio: float = 0.08,
    seed: int = 0,
    diagonal: bool = False,
) -> GridMap:
    """Maze generated by randomized depth-first search (odd dimensions), then a ``loop_ratio`` fraction of inner walls is randomly removed to create multiple paths."""
    rng = np.random.default_rng(seed)
    height, width = height | 1, width | 1
    cell_costs = np.full((height, width), WALL)
    carve_stack = [(1, 1)]
    cell_costs[1, 1] = 1
    while carve_stack:
        row, col = carve_stack[-1]
        unvisited = [
            (row + row_step, col + col_step, row_step, col_step)
            for row_step, col_step in ((-2, 0), (2, 0), (0, -2), (0, 2))
            if 0 < row + row_step < height - 1
            and 0 < col + col_step < width - 1
            and cell_costs[row + row_step, col + col_step] == WALL
        ]
        if not unvisited:
            carve_stack.pop()
            continue
        next_row, next_col, row_step, col_step = unvisited[rng.integers(len(unvisited))]
        cell_costs[row + row_step // 2, col + col_step // 2] = (
            1  # remove the wall between the two cells
        )
        cell_costs[next_row, next_col] = 1
        carve_stack.append((next_row, next_col))
    # remove some inner walls to create loops
    inner_walls = [
        (row, col)
        for row in range(1, height - 1)
        for col in range(1, width - 1)
        if cell_costs[row, col] == WALL and (row % 2) != (col % 2)
    ]
    for wall_index in rng.choice(
        len(inner_walls), int(len(inner_walls) * loop_ratio), replace=False
    ):
        cell_costs[inner_walls[wall_index]] = 1
    return GridMap(
        cell_costs,
        diagonal=diagonal,
        start=(1, 1),
        goal=(height - 2, width - 2),
        name="maze",
    )


def random_obstacle_grid(
    height: int = 60,
    width: int = 90,
    density: float = 0.3,
    seed: int = 0,
    diagonal: bool = True,
) -> GridMap:
    """Random obstacle map (obstacles are rectangles of varying size); start and goal are guaranteed to be connected."""
    from .grid import astar_grid  # avoid circular import

    rng = np.random.default_rng(seed)
    for _attempt in range(100):
        cell_costs = np.ones((height, width))
        while np.isinf(cell_costs).mean() < density:
            block_height, block_width = rng.integers(1, 8, size=2)
            top, left = (
                rng.integers(0, height - block_height),
                rng.integers(0, width - block_width),
            )
            cell_costs[top : top + block_height, left : left + block_width] = WALL
        start, goal = (height - 3, 2), (2, width - 3)
        cell_costs[start[0] - 2 : start[0] + 3, :5] = (
            1  # clear the area around the start
        )
        cell_costs[:5, goal[1] - 2 : goal[1] + 3] = 1  # clear the area around the goal
        grid = GridMap(
            cell_costs, diagonal=diagonal, start=start, goal=goal, name="random"
        )
        if astar_grid(grid).found:
            return grid
        rng = np.random.default_rng(rng.integers(1 << 31))
    raise RuntimeError("could not generate a connected random map; try a lower density")


def _smooth_noise(
    height: int, width: int, rng: np.random.Generator, scale: int = 8
) -> np.ndarray:
    """Simple value noise: a low-resolution random grid + bilinear interpolation, normalized to [0, 1]."""
    coarse_height, coarse_width = height // scale + 2, width // scale + 2
    coarse = rng.random((coarse_height, coarse_width))
    sample_rows = np.linspace(0, coarse_height - 1.001, height)
    sample_cols = np.linspace(0, coarse_width - 1.001, width)
    row_index, col_index = sample_rows.astype(int), sample_cols.astype(int)
    row_fraction = (sample_rows - row_index)[:, None]
    col_fraction = (sample_cols - col_index)[None, :]
    top_left = coarse[np.ix_(row_index, col_index)]
    top_right = coarse[np.ix_(row_index, col_index + 1)]
    bottom_left = coarse[np.ix_(row_index + 1, col_index)]
    bottom_right = coarse[np.ix_(row_index + 1, col_index + 1)]
    top = top_left * (1 - col_fraction) + top_right * col_fraction
    bottom = bottom_left * (1 - col_fraction) + bottom_right * col_fraction
    noise = top * (1 - row_fraction) + bottom * row_fraction
    return (noise - noise.min()) / (np.ptp(noise) or 1)


def weighted_terrain_grid(
    height: int = 60, width: int = 90, seed: int = 0, diagonal: bool = True
) -> GridMap:
    """Weighted terrain: cost 1 (flat) to 9 (mountains), with impassable peaks where the noise is highest,
    plus a "river" with only two crossings. The optimal path detours around high-cost areas instead of going straight."""
    rng = np.random.default_rng(seed)
    elevation = (
        _smooth_noise(height, width, rng, scale=10) * 0.7
        + _smooth_noise(height, width, rng, scale=4) * 0.3
    )
    cell_costs = 1 + np.floor(elevation**1.5 * 9).clip(0, 8)
    cell_costs[elevation > 0.9] = WALL  # peaks
    # River: a vertical wall following a sine curve, with two crossings

    def river_col(row: int) -> int:
        return int(width * 0.55 + 6 * math.sin(row / 6))

    for row in range(height):
        cell_costs[row, river_col(row) : river_col(row) + 2] = WALL
    for bridge_row in (height // 5, height * 4 // 5):
        bridge_col = river_col(bridge_row)
        cell_costs[bridge_row - 1 : bridge_row + 2, bridge_col - 1 : bridge_col + 3] = 1
    start, goal = (height // 2, 2), (height // 2, width - 3)
    cell_costs[start], cell_costs[goal] = 1, 1
    return GridMap(
        cell_costs, diagonal=diagonal, start=start, goal=goal, name="terrain"
    )


